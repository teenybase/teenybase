/**
 * `deploy`/`generate` with --clean (the default) against a target with no settings yet (no
 * .local-persist/config.json, an empty or not yet created D1) delete every .sql file in migrations/
 * and generate a new set from the config. For migrations committed to git that loses the files and
 * renames the history, so the CLI stops before changing anything. A folder git doesn't track (the
 * scaffold gitignores migrations/) keeps the regular behaviour, so `deploy --local` then a first
 * `deploy --remote`, and `generate` then `deploy` on a new project, still work.
 */
import {afterAll, beforeAll, describe, expect, it} from 'vitest'
import {execFileSync, spawnSync} from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {assertCommittedMigrationsKept, gitTrackedFiles} from '../src/node/cli-utils'
import {createLogger} from '../src/node/logger'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const teenyBin = path.join(repoRoot, 'bin', 'teeny.js')
const scratch: string[] = []

function tmpDir(prefix: string) {
    const d = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), prefix))
    scratch.push(d)
    return d
}

function git(cwd: string, ...args: string[]) {
    return execFileSync('git', ['-c', 'user.email=test@example.com', '-c', 'user.name=test', '-c', 'commit.gpgsign=false', ...args], {cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']})
}

function writeFiles(dir: string, files: Record<string, string>) {
    fs.mkdirSync(dir, {recursive: true})
    for (const [name, content] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), content)
}

const committed: Record<string, string> = {
    '00000_create_internal_kv.sql': 'CREATE TABLE IF NOT EXISTS _ddb_internal_kv (key TEXT PRIMARY KEY, value TEXT);\n',
    '10000_create_table_items.sql': '-- Migration number: 10000 generated by teenybase on 2026-10-01T00:00:00.000Z. Do not modify this file.\n\nCREATE TABLE items (id TEXT PRIMARY KEY);\n',
    '10001_create_table_notes.sql': '-- Migration number: 10001 generated by teenybase on 2026-10-02T00:00:00.000Z. Do not modify this file.\n\nCREATE TABLE notes (id TEXT PRIMARY KEY);\n',
}

function readDir(dir: string) {
    if (!fs.existsSync(dir)) return {}
    return Object.fromEntries(fs.readdirSync(dir).sort().map(f => [f, fs.readFileSync(path.join(dir, f), 'utf8')]))
}

afterAll(() => {
    for (const d of scratch) fs.rmSync(d, {recursive: true, force: true})
})

describe('gitTrackedFiles', () => {
    it('lists committed and staged files in the folder, not untracked ones', () => {
        const root = tmpDir('teeny-git-tracked-')
        git(root, 'init', '-q')
        const dir = path.join(root, 'migrations')
        writeFiles(dir, {'a.sql': '1', 'b.sql': '2', 'c.sql': '3'})
        git(root, 'add', 'migrations/a.sql')
        git(root, 'commit', '-q', '-m', 'a')
        git(root, 'add', 'migrations/b.sql') // staged only
        expect(gitTrackedFiles(root, dir, ['a.sql', 'b.sql', 'c.sql'])).toEqual({tracked: ['a.sql', 'b.sql']})
    })

    it('works when the project is a subdirectory of the repository', () => {
        const repo = tmpDir('teeny-git-sub-')
        git(repo, 'init', '-q')
        const root = path.join(repo, 'packages', 'app')
        const dir = path.join(root, 'migrations')
        writeFiles(dir, {'a.sql': '1'})
        writeFiles(path.join(repo, 'migrations'), {'a.sql': 'same name, other folder'})
        git(repo, 'add', 'migrations/a.sql')
        expect(gitTrackedFiles(root, dir, ['a.sql'])).toEqual({tracked: []})
        git(repo, 'add', 'packages/app/migrations/a.sql')
        expect(gitTrackedFiles(root, dir, ['a.sql'])).toEqual({tracked: ['a.sql']})
    })

    it('returns an error outside a repository and when git is not installed', () => {
        const root = tmpDir('teeny-git-none-')
        const dir = path.join(root, 'migrations')
        writeFiles(dir, {'a.sql': '1'})
        // os.tmpdir() could itself be inside a repository; a GIT_CEILING_DIRECTORIES of its parent rules that out
        const ceiling = process.env.GIT_CEILING_DIRECTORIES
        process.env.GIT_CEILING_DIRECTORIES = path.dirname(root)
        try {
            expect(gitTrackedFiles(root, dir, ['a.sql'])).toHaveProperty('error')
        } finally {
            if (ceiling === undefined) delete process.env.GIT_CEILING_DIRECTORIES
            else process.env.GIT_CEILING_DIRECTORIES = ceiling
        }
        const pathEnv = process.env.PATH
        process.env.PATH = ''
        try {
            expect(gitTrackedFiles(root, dir, ['a.sql'])).toHaveProperty('error')
        } finally {
            process.env.PATH = pathEnv
        }
    })
})

describe('assertCommittedMigrationsKept', () => {
    const logger = createLogger('silent')
    function project(track: boolean) {
        const root = tmpDir('teeny-keep-')
        git(root, 'init', '-q')
        writeFiles(path.join(root, 'migrations'), committed)
        if (track) {
            git(root, 'add', 'migrations')
            git(root, 'commit', '-q', '-m', 'migrations')
        }
        return root
    }
    const ctx = (root: string, isLocal: boolean, databaseId = 'TEENY_AUTO_CREATE') => ({
        isLocal,
        root,
        migrationsPath: path.join(root, 'migrations'),
        logger,
        wranglerConfig: {config: {path: path.join(root, 'wrangler.jsonc'), config: {}}, db: {binding: 'PRIMARY_DB', database_id: databaseId, migrations_dir: 'migrations'}, migrations: 'migrations'},
    })
    const names = Object.keys(committed)

    it('stops for committed files and an empty local database', () => {
        const root = project(true)
        expect(() => assertCommittedMigrationsKept(ctx(root, true), names)).toThrow(/has 3 migration files committed to git \(00000_create_internal_kv\.sql \.\.\. 10001_create_table_notes\.sql\), and the local database has no migrations applied/)
        expect(() => assertCommittedMigrationsKept(ctx(root, true), names)).toThrow(/Nothing was changed/)
    })

    it('stops for committed files and an empty or not yet created remote database', () => {
        const root = project(true)
        expect(() => assertCommittedMigrationsKept(ctx(root, false), names)).toThrow(/the remote database hasn't been created yet \(database_id is TEENY_AUTO_CREATE\)/)
        expect(() => assertCommittedMigrationsKept(ctx(root, false, '0123-abcd'), names)).toThrow(/the remote database 0123-abcd has no migrations applied.*\n.*\n.*point database_id in/)
    })

    it('keeps the regular behaviour for files git does not track', () => {
        const root = project(false)
        expect(() => assertCommittedMigrationsKept(ctx(root, true), names)).not.toThrow()
        expect(() => assertCommittedMigrationsKept(ctx(root, false), names)).not.toThrow()
        expect(() => assertCommittedMigrationsKept(ctx(root, true), [])).not.toThrow()
    })

    it('keeps the regular behaviour when git cannot answer', () => {
        const root = project(true)
        const pathEnv = process.env.PATH
        process.env.PATH = ''
        try {
            expect(() => assertCommittedMigrationsKept(ctx(root, true), names)).not.toThrow()
        } finally {
            process.env.PATH = pathEnv
        }
    })
})

describe('teeny deploy with committed migrations and an empty target', () => {
    let projectDir: string
    let migrationsDir: string
    // Nothing here may reach Cloudflare: no credentials, no login, and an API base URL that refuses connections.
    const env = () => ({
        ...process.env,
        FORCE_COLOR: '0',
        CLOUDFLARE_API_TOKEN: '',
        CLOUDFLARE_ACCOUNT_ID: '',
        CLOUDFLARE_API_BASE_URL: 'http://127.0.0.1:9/client/v4',
        HOME: path.join(projectDir, '.home'),
        XDG_CONFIG_HOME: path.join(projectDir, '.home', '.config'),
        TEENY_DEV_PORT: '8979',
        TEENY_INSPECTOR_PORT: '9379',
    })
    function teeny(args: string[]) {
        const res = spawnSync(process.execPath, [teenyBin, ...args], {cwd: projectDir, env: env(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 180_000})
        return {status: res.status, output: `${res.stdout}\n${res.stderr}`}
    }

    beforeAll(() => {
        execFileSync('npm', ['run', 'js-node'], {cwd: repoRoot, stdio: 'pipe', shell: process.platform === 'win32'})
        projectDir = tmpDir('teeny-committed-migrations-')
        fs.mkdirSync(path.join(projectDir, '.home', '.config'), {recursive: true})
        const init = teeny(['init', '--yes', '--no-install', '--template', 'blank'])
        if (init.status !== 0) throw new Error(init.output)
        const modules = path.join(projectDir, 'node_modules')
        fs.mkdirSync(modules, {recursive: true})
        // teenybase.ts imports 'teenybase' (bundled by the config loader); link this repo.
        fs.symlinkSync(repoRoot, path.join(modules, 'teenybase'), process.platform === 'win32' ? 'junction' : 'dir')
        // Commit the migrations like a project that keeps them in git (the scaffold ignores them)
        fs.writeFileSync(path.join(projectDir, '.gitignore'), fs.readFileSync(path.join(projectDir, '.gitignore'), 'utf8').replace(/^migrations\n/m, '') + '.home\n')
        migrationsDir = path.join(projectDir, 'migrations')
        writeFiles(migrationsDir, committed)
        git(projectDir, 'init', '-q')
        git(projectDir, 'add', '-A')
        git(projectDir, 'commit', '-q', '-m', 'init')
    }, 180_000)

    it('deploy --local stops and leaves the files, the database and the local config alone', () => {
        const res = teeny(['deploy', '--local', '--yes'])
        expect(res.output).toContain('3 migration files committed to git')
        expect(res.output).toContain('the local database has no migrations applied')
        expect(res.status).toBe(1)
        expect(readDir(migrationsDir)).toEqual(committed)
        expect(fs.existsSync(path.join(projectDir, '.local-persist'))).toBe(false)
    }, 180_000)

    it('generate --local stops too', () => {
        const res = teeny(['generate', '--local'])
        expect(res.output).toContain('3 migration files committed to git')
        expect(res.status).toBe(1)
        expect(readDir(migrationsDir)).toEqual(committed)
    }, 180_000)

    it('deploy --remote stops before any Cloudflare call', () => {
        const res = teeny(['deploy', '--remote', '--yes'])
        expect(res.output).toContain("the remote database hasn't been created yet (database_id is TEENY_AUTO_CREATE)")
        expect(res.status).toBe(1)
        expect(readDir(migrationsDir)).toEqual(committed)
    }, 180_000)

    it('an untracked folder is still regenerated for an empty target', () => {
        git(projectDir, 'rm', '-q', '--cached', '-r', 'migrations')
        const res = teeny(['generate', '--local'])
        expect(res.output).not.toContain('committed to git')
        expect(res.status).toBe(0)
        // the blank config has no tables: the regular --clean removed the files and generated nothing
        expect(Object.keys(readDir(migrationsDir)).filter(f => f.endsWith('.sql'))).toEqual([])
    }, 180_000)
})
